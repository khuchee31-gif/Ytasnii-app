// Дууны хүрээг ХЭН РҮҮ дамжуулах вэ.
//
// Энэ нь тоглоомын хамгийн эмзэг шийдвэр: буруу бол хоёр алуурчны
// хэлэлцээрийг иргэн сонсоод тоглоом тэр дор нь үхнэ. Тиймээс шийдвэрийг
// сокетээс ТУСГААРЛАЖ, сүлжээгүйгээр шалгана.
//
// `bin/server.dart` нь зөвхөн байт зөөнө; ХЭН сонсохыг энд шийднэ.

import 'package:protocol/protocol.dart';

abstract final class VoiceRelay {
  /// Нэг хүрээг хүлээн авах ёстой хүмүүс.
  ///
  /// Хоёр дүрэм, өөр юу ч биш:
  ///   • Илгээгч нь сувагт байхгүй бол ХЭН Ч сонсохгүй. Апп өөрийгөө
  ///     «ярьж болно» гэж зарлаж болохгүй — эрхийг сервер өгнө.
  ///   • Илгээгч өөрөө өөрийгөө сонсохгүй (цуурай).
  ///
  /// Буцаах жагсаалт нь хоосон байх нь ХЭВИЙН: эмч шөнө ганцаараа байдаг
  /// тул түүний дуу хаашаа ч явахгүй. Тэр тохиолдолд ч микрофон нээлттэй
  /// байж болно — хүн өөрийгөө сонсох нь тоглоомд саад болохгүй.
  static List<PlayerId> recipients({
    required PlayerId from,
    required Set<PlayerId> channel,
  }) {
    if (!channel.contains(from)) return const <PlayerId>[];
    return channel
        .where((PlayerId id) => id != from)
        .toList(growable: false);
  }
}
